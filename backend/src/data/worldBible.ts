export function describeBloodGauge(gauge: number): string {
  if (!gauge || gauge <= 0) return 'нет следов демонической силы'
  if (gauge <= 3) return 'ранние признаки: усталость после убийств, чужие сны'
  if (gauge <= 6) return 'заметные изменения: тело реагирует быстрее разума'
  if (gauge <= 9) return 'глубокие мутации: сила огромна, человечность под угрозой'
  return 'на пороге финального выбора: человек или демон'
}
